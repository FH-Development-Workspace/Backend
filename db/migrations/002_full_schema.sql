CREATE TABLE IF NOT EXISTS categories (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(255) NOT NULL UNIQUE,
  slug VARCHAR(255) NOT NULL UNIQUE,
  description TEXT,
  icon VARCHAR(255),
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
  id CHAR(36) PRIMARY KEY,
  category_id CHAR(36),
  name VARCHAR(255) NOT NULL,
  slug VARCHAR(255) NOT NULL UNIQUE,
  summary TEXT,
  description TEXT NOT NULL,
  price_gbp DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
  is_free TINYINT(1) NOT NULL DEFAULT 0,
  status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
  featured TINYINT(1) NOT NULL DEFAULT 0,
  banner_url TEXT,
  icon_url TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS product_versions (
  id CHAR(36) PRIMARY KEY,
  product_id CHAR(36) NOT NULL,
  version VARCHAR(100) NOT NULL,
  changelog TEXT,
  status VARCHAR(50) NOT NULL DEFAULT 'RELEASED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(product_id, version),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS product_files (
  id CHAR(36) PRIMARY KEY,
  version_id CHAR(36) NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_path TEXT NOT NULL,
  file_size BIGINT NOT NULL DEFAULT 0,
  mime_type VARCHAR(255),
  visibility VARCHAR(50) NOT NULL DEFAULT 'LICENSED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (version_id) REFERENCES product_versions(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS product_dependencies (
  id CHAR(36) PRIMARY KEY,
  product_id CHAR(36) NOT NULL,
  depends_on_product_id CHAR(36) NOT NULL,
  required_version VARCHAR(100),
  UNIQUE(product_id, depends_on_product_id),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
  FOREIGN KEY (depends_on_product_id) REFERENCES products(id) ON DELETE CASCADE
);

